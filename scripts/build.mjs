// Builds the static site: src/pages/*.html + src/partials/*.html + site.config.json
// -> *.html, sitemap.xml, robots.txt and CNAME at the output root (repo root by default).
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, basename, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { render, parsePage } from './lib/render.mjs';
import { loadConfig, buildContext, fileForPath, sitemapXml, robotsTxt } from './lib/site.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BANNER = '<!-- Generated by scripts/build.mjs — edit src/ instead -->\n';
const PAGE_ORDER = ['/', '/about', '/services', '/portfolio', '/contact'];

function readDir(dir) {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.html'))
    .sort()
    .map((f) => ({ name: basename(f, '.html'), source: readFileSync(join(dir, f), 'utf8') }));
}

// Renders every page and returns { files: { [name]: content } } without touching disk.
export function renderSite({ root = ROOT, year } = {}) {
  const config = loadConfig(join(root, 'site.config.json'));
  const partials = Object.fromEntries(readDir(join(root, 'src/partials')).map((p) => [p.name, p.source]));
  if (!partials.layout) throw new Error('src/partials/layout.html is missing');

  const files = {};
  const pages = [];
  for (const { name, source } of readDir(join(root, 'src/pages'))) {
    try {
      const { meta, body } = parsePage(source);
      const file = fileForPath(meta.path);
      if (files[file]) throw new Error(`path "${meta.path}" is used by more than one page`);
      const ctx = buildContext(config, meta, year === undefined ? {} : { year });
      const html = render('{{> layout}}', ctx, { ...partials, body });
      // Banner goes right after the doctype so the doctype stays the first token.
      files[file] = html.replace(/^(<!doctype html>\n)/i, `$1${BANNER}`);
      pages.push(meta);
    } catch (err) {
      err.message = `src/pages/${name}.html: ${err.message}`;
      throw err;
    }
  }

  const url = `https://${config.domain}`;
  const rank = (p) => (PAGE_ORDER.indexOf(p.path) + 1 || PAGE_ORDER.length + 1);
  files['sitemap.xml'] = sitemapXml(url, [...pages].sort((a, b) => rank(a) - rank(b)));
  files['robots.txt'] = robotsTxt(url);
  files.CNAME = `${config.domain}\n`;
  return { files };
}

export function buildSite({ root = ROOT, outDir = root, year } = {}) {
  const { files } = renderSite({ root, year });
  mkdirSync(outDir, { recursive: true });
  for (const [name, content] of Object.entries(files)) writeFileSync(join(outDir, name), content);
  return Object.keys(files);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const written = buildSite();
    console.log(`Built ${written.length} files: ${written.join(', ')}`);
  } catch (err) {
    console.error(`build failed: ${err.message}`);
    process.exit(1);
  }
}
